const ETIQUETA_VALORACION = {
    showcase_most_sold: 3,
    showcase_favorite: 2,
    showcase_featured: 1,
};

const ORDEN_GENERO = {
    category_female: 0,
    category_male: 1,
    category_unisex: 2,
};

const CRITERIOS_ORDEN = [
    "az",
    "za",
    "mayor",
    "menor",
    "valoracion",
    "genero",
];

function valoracionDeProducto(producto) {
    return ETIQUETA_VALORACION[producto.etiqueta] || 0;
}

function compararProductos(a, b, criterio) {
    const porNombre = String(a.nombre).localeCompare(String(b.nombre), "es", {
        sensitivity: "base",
    });

    switch (criterio) {
        case "za":
            return -porNombre;

        case "mayor":
            return Number(b.precio) - Number(a.precio) || porNombre;

        case "menor":
            return Number(a.precio) - Number(b.precio) || porNombre;

        case "valoracion":
            return valoracionDeProducto(b) - valoracionDeProducto(a) || porNombre;

        case "genero": {
            const diferencia =
                (ORDEN_GENERO[a.categoria] || 0) - (ORDEN_GENERO[b.categoria] || 0);
            return diferencia || porNombre;
        }

        case "az":
        default:
            return porNombre;
    }
}

function ordenarProductos(lista, criterio) {
    return lista.slice().sort(function (a, b) {
        return compararProductos(a, b, criterio);
    });
}
